use std::{
    collections::VecDeque,
    num::NonZeroUsize,
};

use getset::CopyGetters;
use num::Float;

use super::ultimate_smoother::UltimateCore;
use crate::View;

/// Maximum Laguerre filter order, the array size in the published code.
const MAX_ORDER: usize = 10;

/// `Variance` below this many ulps of the filter level counts as 0, see struct docs.
const NOISE_ULPS: f64 = 64.0;

/// John Ehlers Continuation Index (CI).
///
/// A two-state trend indicator: near +1 while price trends up (stays above a
/// Laguerre filter), near -1 while it trends down. The change of state marks
/// trend exhaustion / onset with little lag.
///
/// Reference: John Ehlers, "The Continuation Index", Technical Analysis of
/// Stocks & Commodities, September 2025, and
/// <https://www.mesasoftware.com/papers/Continuation%20Index.pdf>
/// (Code Listings 1 to 3):
///
/// ```text
/// US       = UltimateSmoother(x, Length / 2)
/// LG[1]    = UltimateSmoother(x, Length)
/// LG[k]    = -gamma LG[k-1][1] + LG[k-1][1] + gamma LG[k][1],   k = 2..=order
/// LG       = sum_{k=1}^{order} LG[k] / order
/// Variance = SMA(|US - LG|, Length)
/// Ref      = 2 (US - LG) / Variance                 // kept when Variance = 0
/// CI       = (exp(2 Ref) - 1) / (exp(2 Ref) + 1)
/// ```
///
/// The Laguerre stages read the previous bar's values of both neighbours, as
/// in the published `$Laguerre` function (not the classic Laguerre filter of
/// the crate's [`LaguerreFilter`](super::LaguerreFilter)).
///
/// Deviations:
/// - The Laguerre components start at the first input instead of 0, so the
///   filter starts at rest instead of rising from 0 for many bars.
/// - The Inverse Fisher Transform is computed as `tanh(Ref)`, which is
///   algebraically identical but cannot overflow in `exp`.
/// - `Length / 2` is a fractional period for odd lengths, as in EasyLanguage.
/// - `If Variance <> 0` becomes `Variance > 64 ulps of |LG|`, because the
///   filters' rounding noise makes `Variance` tiny but non-zero for a constant
///   input, and `Ref` would then be a ratio of noise terms.
///
/// `last()` is `None` for the first `length - 1` values.
///
/// Output range: `[-1, 1]`. Constant input yields 0.
/// Complexity: O(order) = O(1) per update (`order <= 10`), amortized O(1) for
/// the moving average of `|US - LG|` (running sum, recomputed every `length`
/// updates to stop floating point drift); O(length) memory.
#[derive(Debug, Clone, CopyGetters)]
pub struct ContinuationIndex<T, V> {
    view: V,
    gamma: T,
    /// The order of the Laguerre filter, in `1..=10`.
    #[getset(get_copy = "pub")]
    order: usize,
    /// The period of the Laguerre filter's smoother and of the average difference.
    #[getset(get_copy = "pub")]
    length: NonZeroUsize,
    /// UltimateSmoother at `length / 2`.
    us_fast: UltimateCore<T>,
    /// UltimateSmoother at `length`, the first Laguerre component.
    us_slow: UltimateCore<T>,
    /// Laguerre components `LG[1..=order]`, unused beyond `order`.
    lg: [T; MAX_ORDER],
    /// `|US - LG|` of the last `length` values.
    abs_diffs: VecDeque<T>,
    sum_abs_diff: T,
    /// Updates since `sum_abs_diff` was last recomputed from scratch.
    since_recompute: usize,
    reference: T,
}

impl<T, V> ContinuationIndex<T, V>
where
    V: View<T>,
    T: Float,
{
    /// Create a new Continuation Index with a chained `View`.
    ///
    /// Ehlers' defaults are `gamma = 0.8`, `order = 8`, `length = 40`.
    ///
    /// # Panics
    /// - If `gamma` is not in `[0, 1)`.
    /// - If `order` is not in `1..=10`.
    /// - If `length < 4`, as the UltimateSmoother period `length / 2` must be at least 2.
    pub fn new(view: V, gamma: T, order: usize, length: NonZeroUsize) -> Self {
        assert!(gamma >= T::zero(), "gamma must be >= 0");
        assert!(gamma < T::one(), "gamma must be < 1");
        assert!(order >= 1, "order must be >= 1");
        assert!(order <= MAX_ORDER, "order must be <= 10");
        assert!(length.get() >= 4, "length must be >= 4");
        let len = T::from(length.get()).expect("can convert");
        Self {
            view,
            gamma,
            order,
            length,
            us_fast: UltimateCore::new(len / T::from(2.0).expect("can convert")),
            us_slow: UltimateCore::new(len),
            lg: [T::zero(); MAX_ORDER],
            abs_diffs: VecDeque::with_capacity(length.get()),
            sum_abs_diff: T::zero(),
            since_recompute: 0,
            reference: T::zero(),
        }
    }

    /// The Laguerre damping factor, in `[0, 1)`.
    // Not generated by `getset`, as its impl block lacks the `T: Copy` bound.
    #[inline]
    pub fn gamma(&self) -> T {
        self.gamma
    }

    /// Advance the Laguerre components with the new first component and return their mean.
    fn update_laguerre(&mut self, first: T, is_first_value: bool) -> T {
        let order = self.order;
        if is_first_value {
            // Start at rest, see struct docs.
            self.lg[..order].fill(first);
        }
        let prev = self.lg;
        for k in 1..order {
            self.lg[k] = -self.gamma * prev[k - 1] + prev[k - 1] + self.gamma * prev[k];
        }
        self.lg[0] = first;
        let sum = self.lg[..order].iter().fold(T::zero(), |acc, v| acc + *v);
        sum / T::from(order).expect("can convert")
    }

    /// Push `|US - LG|` into the averaging window and return the new average.
    fn push_abs_diff(&mut self, abs_diff: T) -> T {
        let len = self.length.get();
        if self.abs_diffs.len() == len {
            let old = self.abs_diffs.pop_front().expect("the window is full");
            self.sum_abs_diff = self.sum_abs_diff - old;
        }
        self.abs_diffs.push_back(abs_diff);
        self.sum_abs_diff = self.sum_abs_diff + abs_diff;
        self.since_recompute += 1;
        if self.since_recompute >= len {
            // Exact sum, so rounding errors of the running sum cannot accumulate.
            self.sum_abs_diff = self.abs_diffs.iter().fold(T::zero(), |acc, v| acc + *v);
            self.since_recompute = 0;
        }
        debug_assert!(self.abs_diffs.len() <= len);
        self.sum_abs_diff.max(T::zero()) / T::from(self.abs_diffs.len()).expect("can convert")
    }
}

impl<T, V> View<T> for ContinuationIndex<T, V>
where
    V: View<T>,
    T: Float,
{
    fn update(&mut self, val: T) {
        debug_assert!(val.is_finite(), "value must be finite");
        self.view.update(val);
        let Some(val) = self.view.last() else { return };
        debug_assert!(val.is_finite(), "value must be finite");

        let is_first_value = self.abs_diffs.is_empty();
        let us = self.us_fast.update(val);
        let first = self.us_slow.update(val);
        let lg = self.update_laguerre(first, is_first_value);
        let diff = us - lg;
        let variance = self.push_abs_diff(diff.abs());
        // Rounding noise of the filters makes `Variance` tiny but non-zero for a
        // constant input, and the ratio of two noise terms is meaningless.
        let noise_floor = T::from(NOISE_ULPS).expect("can convert") * T::epsilon() * lg.abs();
        if variance > noise_floor {
            self.reference = T::from(2.0).expect("can convert") * diff / variance;
        }
        debug_assert!(self.reference.is_finite(), "reference must be finite");
    }

    #[inline]
    fn last(&self) -> Option<T> {
        if self.abs_diffs.len() < self.length.get() {
            return None;
        }
        // The Inverse Fisher Transform `(e^2r - 1) / (e^2r + 1)` is `tanh(r)`.
        let out = self.reference.tanh();
        debug_assert!(out.is_finite(), "value must be finite");
        debug_assert!(out.abs() <= T::one(), "output must be in [-1, 1]");
        Some(out)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::{
        plot::plot_values,
        pure_functions::Echo,
        test_data::TEST_DATA,
    };

    fn ci(gamma: f64, order: usize, length: usize) -> ContinuationIndex<f64, Echo<f64>> {
        ContinuationIndex::new(
            Echo::new(),
            gamma,
            order,
            NonZeroUsize::new(length).unwrap(),
        )
    }

    /// Transcription of the published code listings (with this crate's start at rest).
    fn reference(prices: &[f64], gamma: f64, order: usize, length: usize) -> Vec<f64> {
        let ultimate = |period: f64| -> Vec<f64> {
            // Listing 2, with `Q`, `c1`, `c2`, `a0` as published.
            let ehlers_pi = 314_159.0 / 100_000.0;
            let q = (-1.414 * ehlers_pi / period).exp();
            let c1 = 2.0 * q * (1.414 * 180.0 / period).to_radians().cos();
            let c2 = q * q;
            let a0 = (1.0 + c1 + c2) / 4.0;
            let mut us: Vec<f64> = Vec::new();
            for i in 0..prices.len() {
                let v = if i < 3 {
                    prices[i]
                } else {
                    (1.0 - a0) * prices[i]
                        + (2.0 * a0 - c1) * prices[i - 1]
                        + (c2 - a0) * prices[i - 2]
                        + c1 * us[i - 1]
                        - c2 * us[i - 2]
                };
                us.push(v);
            }
            us
        };
        let us = ultimate(length as f64 / 2.0);
        let first = ultimate(length as f64);
        // Listing 3, 1-based arrays `LG[count, 1]` (current) and `LG[count, 2]` (previous).
        let mut cur = [prices[0]; MAX_ORDER + 1];
        let mut prv = [prices[0]; MAX_ORDER + 1];
        let mut diffs: Vec<f64> = Vec::new();
        let mut r = 0.0;
        let mut out = Vec::new();
        for i in 0..prices.len() {
            // `For count = 1 to order Begin LG[count, 2] = LG[count, 1]`.
            prv[1..=order].copy_from_slice(&cur[1..=order]);
            for count in 2..=order {
                cur[count] = -gamma * prv[count - 1] + prv[count - 1] + gamma * prv[count];
            }
            cur[1] = first[i];
            let lg = cur[1..=order].iter().sum::<f64>() / order as f64;
            // Listing 1.
            diffs.push((us[i] - lg).abs());
            let tail = &diffs[diffs.len().saturating_sub(length)..];
            let variance = tail.iter().sum::<f64>() / tail.len() as f64;
            if variance != 0.0 {
                r = 2.0 * (us[i] - lg) / variance;
            }
            out.push(((2.0 * r).exp() - 1.0) / ((2.0 * r).exp() + 1.0));
        }
        out
    }

    #[test]
    fn continuation_index_plot() {
        let mut f = ci(0.8, 8, 40);
        let mut out: Vec<f64> = Vec::with_capacity(TEST_DATA.len());
        for v in &TEST_DATA {
            f.update(*v);
            if let Some(val) = f.last() {
                out.push(val);
            }
        }
        plot_values(out, "img/continuation_index.png").unwrap();
    }

    #[test]
    fn continuation_index_warmup() {
        let mut f = ci(0.8, 8, 10);
        assert_eq!(f.gamma(), 0.8);
        assert_eq!(f.order(), 8);
        assert_eq!(f.length().get(), 10);
        for i in 0..9 {
            f.update(i as f64);
            assert_eq!(f.last(), None);
        }
        f.update(9.0);
        assert!(f.last().is_some());
    }

    #[test]
    fn continuation_index_matches_published_code() {
        for (gamma, order, length) in [(0.8, 8, 40), (0.4, 4, 21), (0.0, 1, 4), (0.9, 10, 30)] {
            let want = reference(&TEST_DATA, gamma, order, length);
            let mut f = ci(gamma, order, length);
            for (i, v) in TEST_DATA.iter().enumerate() {
                f.update(*v);
                if let Some(got) = f.last() {
                    // 3.14159 vs exact pi.
                    assert!(
                        (got - want[i]).abs() < 1e-3,
                        "{gamma} {order} {length} bar {i}: {got} vs {}",
                        want[i]
                    );
                }
            }
        }
    }

    #[test]
    fn continuation_index_constant_input_is_zero() {
        let mut f = ci(0.8, 8, 20);
        for _ in 0..200 {
            f.update(42.0);
        }
        assert_eq!(f.last(), Some(0.0));
    }

    #[test]
    fn continuation_index_trend_states() {
        let rng = romu::Rng::from_seed_with_64bit(23);
        let mut f = ci(0.8, 8, 40);
        let mut x = 100.0;
        for i in 0..400 {
            x += if i < 200 { 0.5 } else { -0.5 } + rng.f64() - 0.5;
            f.update(x);
            let Some(out) = f.last() else { continue };
            assert!(out.abs() <= 1.0);
            if i == 199 {
                assert!(out > 0.9, "uptrend {out}");
            }
        }
        assert!(f.last().unwrap() < -0.9, "downtrend {:?}", f.last());
    }

    #[test]
    #[should_panic(expected = "gamma must be < 1")]
    fn continuation_index_gamma_one() {
        let _ = ci(1.0, 8, 40);
    }

    #[test]
    #[should_panic(expected = "gamma must be >= 0")]
    fn continuation_index_gamma_negative() {
        let _ = ci(-0.1, 8, 40);
    }

    #[test]
    #[should_panic(expected = "gamma must be >= 0")]
    fn continuation_index_gamma_nan() {
        let _ = ci(f64::NAN, 8, 40);
    }

    #[test]
    #[should_panic(expected = "order must be >= 1")]
    fn continuation_index_order_zero() {
        let _ = ci(0.8, 0, 40);
    }

    #[test]
    #[should_panic(expected = "order must be <= 10")]
    fn continuation_index_order_too_large() {
        let _ = ci(0.8, 11, 40);
    }

    #[test]
    #[should_panic(expected = "length must be >= 4")]
    fn continuation_index_length_too_small() {
        let _ = ci(0.8, 8, 3);
    }
}
