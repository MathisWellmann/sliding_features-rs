use std::{
    collections::VecDeque,
    num::NonZeroUsize,
};

use getset::CopyGetters;
use num::Float;

use super::ultimate_smoother::UltimateCore;
use crate::View;

/// John Ehlers Ultimate Bands.
///
/// Volatility bands around an [`UltimateSmoother`](super::UltimateSmoother):
///
/// ```text
/// center    = UltimateSmoother(x, P)
/// deviation = sqrt(sum_{k=0}^{P-1} (x[k] - center[k])^2 / P)
/// upper     = center + num_sds * deviation
/// lower     = center - num_sds * deviation
/// ```
///
/// Like Bollinger Bands, but the deviation is measured around the smoother
/// instead of around a lagging simple moving average, so the bands follow
/// trends with almost no lag.
///
/// Reference: John Ehlers, "Ultimate Channel and Ultimate Bands",
/// Technical Analysis of Stocks & Commodities, November 2024.
/// The Ultimate Channel of the same article needs high, low and true range
/// and is therefore not implemented.
///
/// Deviation: the published code keeps the previous deviation when the sum of
/// squares is exactly 0 (`If SumSq <> 0 Then ...`); here the deviation is 0 then.
///
/// `last()` returns the center line and is `None` for the first `period - 1` values.
/// See [`upper`](Self::upper), [`lower`](Self::lower) and [`deviation`](Self::deviation)
/// for the other outputs.
///
/// Output range: unbounded, follows the input; `lower <= center <= upper`.
/// Complexity: amortized O(1) per update (the running sum of squares is
/// recomputed every `period` updates to stop floating point drift), O(period) memory.
#[derive(Debug, Clone, CopyGetters)]
pub struct UltimateBands<T, V> {
    view: V,
    /// The period of the smoother and of the deviation window.
    #[getset(get_copy = "pub")]
    period: NonZeroUsize,
    num_sds: T,
    core: UltimateCore<T>,
    /// Squared residuals `(x - center)^2` of the last `period` values.
    sq_residuals: VecDeque<T>,
    sum_sq: T,
    /// Updates since `sum_sq` was last recomputed from scratch.
    since_recompute: usize,
}

impl<T, V> UltimateBands<T, V>
where
    V: View<T>,
    T: Float,
{
    /// Create new Ultimate Bands with a chained `View`.
    ///
    /// `num_sds` is the band width in deviations, Ehlers uses 1.
    ///
    /// # Panics
    /// - If `period < 2`, as shorter periods are above the Nyquist frequency.
    /// - If `num_sds` is not positive and finite.
    pub fn new(view: V, period: NonZeroUsize, num_sds: T) -> Self {
        assert!(period.get() >= 2, "period must be >= 2");
        assert!(num_sds.is_finite(), "num_sds must be finite");
        assert!(num_sds > T::zero(), "num_sds must be > 0");
        Self {
            view,
            period,
            num_sds,
            core: UltimateCore::new(T::from(period.get()).expect("can convert")),
            sq_residuals: VecDeque::with_capacity(period.get()),
            sum_sq: T::zero(),
            since_recompute: 0,
        }
    }

    /// The band width in deviations.
    // Not generated by `getset`, as its impl block lacks the `T: Copy` bound.
    #[inline]
    pub fn num_sds(&self) -> T {
        self.num_sds
    }

    /// The root mean square distance between input and center line over `period`.
    pub fn deviation(&self) -> Option<T> {
        self.last()?;
        let mean_sq = self.sum_sq.max(T::zero()) / T::from(self.period.get()).expect("can convert");
        let dev = mean_sq.sqrt();
        debug_assert!(dev.is_finite(), "deviation must be finite");
        debug_assert!(dev >= T::zero(), "deviation must not be negative");
        Some(dev)
    }

    /// The upper band, `center + num_sds * deviation`.
    pub fn upper(&self) -> Option<T> {
        Some(self.last()? + self.num_sds * self.deviation()?)
    }

    /// The lower band, `center - num_sds * deviation`.
    pub fn lower(&self) -> Option<T> {
        Some(self.last()? - self.num_sds * self.deviation()?)
    }
}

impl<T, V> View<T> for UltimateBands<T, V>
where
    V: View<T>,
    T: Float,
{
    fn update(&mut self, val: T) {
        debug_assert!(val.is_finite(), "value must be finite");
        self.view.update(val);
        let Some(val) = self.view.last() else { return };
        debug_assert!(val.is_finite(), "value must be finite");

        let center = self.core.update(val);
        let residual = val - center;
        let sq = residual * residual;
        if self.sq_residuals.len() == self.period.get() {
            let old = self.sq_residuals.pop_front().expect("the window is full");
            self.sum_sq = self.sum_sq - old;
        }
        self.sq_residuals.push_back(sq);
        self.sum_sq = self.sum_sq + sq;
        self.since_recompute += 1;
        if self.since_recompute >= self.period.get() {
            // Exact sum, so rounding errors of the running sum cannot accumulate.
            self.sum_sq = self.sq_residuals.iter().fold(T::zero(), |acc, v| acc + *v);
            self.since_recompute = 0;
        }
        debug_assert!(self.sq_residuals.len() <= self.period.get());
        debug_assert!(self.sum_sq.is_finite(), "sum of squares must be finite");
    }

    #[inline]
    fn last(&self) -> Option<T> {
        if self.sq_residuals.len() < self.period.get() {
            return None;
        }
        let out = self.core.value();
        debug_assert!(out.is_finite(), "value must be finite");
        Some(out)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::{
        plot::plot_values,
        pure_functions::Echo,
        sliding_windows::UltimateSmoother,
        test_data::TEST_DATA,
    };

    fn bands(period: usize, num_sds: f64) -> UltimateBands<f64, Echo<f64>> {
        UltimateBands::new(Echo::new(), NonZeroUsize::new(period).unwrap(), num_sds)
    }

    #[test]
    fn ultimate_bands_plot() {
        let mut f = bands(20, 1.0);
        let mut out: Vec<f64> = Vec::with_capacity(TEST_DATA.len());
        for v in &TEST_DATA {
            f.update(*v);
            if let Some(val) = f.upper() {
                out.push(val);
            }
        }
        plot_values(out, "img/ultimate_bands.png").unwrap();
    }

    #[test]
    fn ultimate_bands_warmup() {
        let mut f = bands(10, 1.0);
        assert_eq!(f.period().get(), 10);
        assert_eq!(f.num_sds(), 1.0);
        for i in 0..9 {
            f.update(i as f64);
            assert_eq!(f.last(), None);
            assert_eq!(f.upper(), None);
            assert_eq!(f.lower(), None);
            assert_eq!(f.deviation(), None);
        }
        f.update(9.0);
        assert!(f.last().is_some());
        assert!(f.upper().is_some());
        assert!(f.lower().is_some());
        assert!(f.deviation().is_some());
    }

    #[test]
    fn ultimate_bands_matches_direct_computation() {
        let (p, k) = (12, 1.5);
        let mut f = bands(p, k);
        let mut us = UltimateSmoother::new(Echo::new(), NonZeroUsize::new(p).unwrap());
        let mut core = UltimateCore::new(p as f64);
        let mut residuals: Vec<f64> = Vec::new();
        for v in TEST_DATA {
            f.update(v);
            us.update(v);
            residuals.push(v - core.update(v));
            let Some(center) = f.last() else { continue };
            assert_eq!(Some(center), us.last());
            let tail = &residuals[residuals.len() - p..];
            let sd = (tail.iter().map(|r| r * r).sum::<f64>() / p as f64).sqrt();
            assert!((f.deviation().unwrap() - sd).abs() < 1e-9);
            assert!((f.upper().unwrap() - (center + k * sd)).abs() < 1e-9);
            assert!((f.lower().unwrap() - (center - k * sd)).abs() < 1e-9);
        }
    }

    #[test]
    fn ultimate_bands_constant_input() {
        let mut f = bands(20, 2.0);
        for _ in 0..100 {
            f.update(42.0);
        }
        assert!((f.last().unwrap() - 42.0).abs() < 1e-10);
        assert!(f.deviation().unwrap() < 1e-10);
        assert!((f.upper().unwrap() - 42.0).abs() < 1e-9);
        assert!((f.lower().unwrap() - 42.0).abs() < 1e-9);
    }

    #[test]
    fn ultimate_bands_ordering_and_width() {
        let mut f = bands(20, 2.0);
        let rng = romu::Rng::from_seed_with_64bit(11);
        for i in 0..5_000 {
            f.update(100.0 + (i as f64 * 0.05).sin() * 5.0 + rng.f64());
            let (Some(c), Some(u), Some(l), Some(d)) =
                (f.last(), f.upper(), f.lower(), f.deviation())
            else {
                continue;
            };
            assert!(l <= c);
            assert!(c <= u);
            assert!(((u - l) - 4.0 * d).abs() < 1e-9);
            assert!(d > 0.0);
            assert!(d < 5.0);
        }
    }

    #[test]
    #[should_panic(expected = "period must be >= 2")]
    fn ultimate_bands_period_too_small() {
        let _ = bands(1, 1.0);
    }

    #[test]
    #[should_panic(expected = "num_sds must be > 0")]
    fn ultimate_bands_num_sds_zero() {
        let _ = bands(20, 0.0);
    }

    #[test]
    #[should_panic(expected = "num_sds must be finite")]
    fn ultimate_bands_num_sds_nan() {
        let _ = bands(20, f64::NAN);
    }
}
