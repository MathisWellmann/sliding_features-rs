//! T3 - Tillson's Triple Exponential Moving Average

use std::num::NonZeroUsize;

use getset::CopyGetters;
use num::Float;

use crate::{
    View,
    pure_functions::Echo,
    sliding_windows::Ema,
};

/// T3 - Tillson's Triple Exponential Moving Average (Tim Tillson, "Smoothing
/// Techniques For More Accurate Signals", Technical Analysis of Stocks &
/// Commodities, 1998; also TA-Lib's `T3`).
///
/// Six chained EMAs `e1..e6` of `x` (each the EMA of the previous one, all
/// sharing `window_len`) combined with the volume factor `v` (`0 <= v <= 1`,
/// default `0.7`) as
///
/// `T3 = c1*e6 + c2*e5 + c3*e4 + c4*e3`, with
/// `c1 = -v^3`, `c2 = 3v^2 + 3v^3`, `c3 = -6v^2 - 3v - 3v^3`,
/// `c4 = 1 + 3v + v^3 + 3v^2`.
///
/// `v = 0` degenerates to a plain EMA (`c4 = 1`, the rest `0`); larger `v`
/// trades a smoother curve for more lag. `last()` is `None` until `e6` is
/// ready, which needs about `6 * window_len - 5` input values.
///
/// Complexity: O(1) per update (six chained EMA updates); O(1) memory.
#[derive(Debug, Clone, CopyGetters)]
pub struct T3<T, V> {
    view: V,
    /// The non-zero window length shared by all six inner EMAs.
    #[getset(get_copy = "pub")]
    window_len: NonZeroUsize,
    /// The volume factor, in `[0, 1]`.
    volume_factor: T,
    c1: T,
    c2: T,
    c3: T,
    c4: T,
    ema1: Ema<T, Echo<T>>,
    ema2: Ema<T, Echo<T>>,
    ema3: Ema<T, Echo<T>>,
    ema4: Ema<T, Echo<T>>,
    ema5: Ema<T, Echo<T>>,
    ema6: Ema<T, Echo<T>>,
    out: Option<T>,
}

impl<T, V> T3<T, V>
where
    V: View<T>,
    T: Float,
{
    /// Create a new T3 with a chained `View`, a window length and the
    /// default volume factor of `0.7`.
    pub fn new(view: V, window_len: NonZeroUsize) -> Self {
        Self::with_volume_factor(view, window_len, T::from(0.7).expect("can convert"))
    }

    /// Create a new T3 with a chained `View`, a window length and a custom
    /// volume factor.
    ///
    /// # Panics
    /// If `volume_factor` is not in `[0, 1]`.
    pub fn with_volume_factor(view: V, window_len: NonZeroUsize, volume_factor: T) -> Self {
        assert!(volume_factor >= T::zero(), "volume_factor must be >= 0");
        assert!(volume_factor <= T::one(), "volume_factor must be <= 1");

        let v = volume_factor;
        let three = T::from(3.0).expect("can convert");
        let six = T::from(6.0).expect("can convert");
        let v2 = v * v;
        let v3 = v2 * v;
        let c1 = -v3;
        let c2 = three * v2 + three * v3;
        let c3 = -six * v2 - three * v - three * v3;
        let c4 = T::one() + three * v + v3 + three * v2;

        Self {
            view,
            window_len,
            volume_factor,
            c1,
            c2,
            c3,
            c4,
            ema1: Ema::new(Echo::new(), window_len),
            ema2: Ema::new(Echo::new(), window_len),
            ema3: Ema::new(Echo::new(), window_len),
            ema4: Ema::new(Echo::new(), window_len),
            ema5: Ema::new(Echo::new(), window_len),
            ema6: Ema::new(Echo::new(), window_len),
            out: None,
        }
    }

    /// The volume factor in `[0, 1]`.
    // Not generated by `getset`, as the struct's generic `T` is not bounded
    // by `Copy` at the type level, only within this impl block.
    #[inline]
    pub fn volume_factor(&self) -> T {
        self.volume_factor
    }
}

impl<T, V> View<T> for T3<T, V>
where
    V: View<T>,
    T: Float,
{
    fn update(&mut self, val: T) {
        debug_assert!(val.is_finite(), "value must be finite");
        self.view.update(val);
        let Some(val) = self.view.last() else { return };
        debug_assert!(val.is_finite(), "value must be finite");

        self.ema1.update(val);
        let Some(e1) = self.ema1.last() else { return };
        self.ema2.update(e1);
        let Some(e2) = self.ema2.last() else { return };
        self.ema3.update(e2);
        let Some(e3) = self.ema3.last() else { return };
        self.ema4.update(e3);
        let Some(e4) = self.ema4.last() else { return };
        self.ema5.update(e4);
        let Some(e5) = self.ema5.last() else { return };
        self.ema6.update(e5);
        let Some(e6) = self.ema6.last() else { return };

        self.out = Some(self.c1 * e6 + self.c2 * e5 + self.c3 * e4 + self.c4 * e3);
    }

    fn last(&self) -> Option<T> {
        self.out.inspect(|v| {
            debug_assert!(v.is_finite(), "value must be finite");
        })
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::{
        plot::plot_values,
        test_data::TEST_DATA,
    };

    #[test]
    fn t3_warms_up() {
        let mut t3 = T3::new(Echo::new(), NonZeroUsize::new(3).unwrap());
        // Warm-up is `6 * window_len - 5 = 13` input values.
        for v in &TEST_DATA[..12] {
            t3.update(*v);
            assert_eq!(t3.last(), None);
        }
        for v in &TEST_DATA {
            t3.update(*v);
        }
        assert!(t3.last().is_some());
    }

    #[test]
    fn t3_constant_input_is_the_constant() {
        let mut t3 = T3::new(Echo::new(), NonZeroUsize::new(4).unwrap());
        for _ in 0..60 {
            t3.update(2.25);
        }
        assert!((t3.last().expect("ready") - 2.25).abs() < 1e-9);
    }

    /// With `v = 0`, `c4 = 1` and the rest vanish, so T3 degenerates to `e3`,
    /// the triple-EMA chain without any combination (a sanity check on the
    /// coefficients, not a claim that T3 equals a plain EMA).
    #[test]
    fn t3_with_zero_volume_factor_is_the_triple_ema_chain() {
        let window_len = NonZeroUsize::new(5).unwrap();
        let mut t3 = T3::with_volume_factor(Echo::new(), window_len, 0.0);
        let mut e1 = Ema::new(Echo::new(), window_len);
        let mut e2 = Ema::new(Echo::new(), window_len);
        let mut e3 = Ema::new(Echo::new(), window_len);
        for v in &TEST_DATA {
            t3.update(*v);
            e1.update(*v);
            if let Some(v1) = e1.last() {
                e2.update(v1);
            }
            if let Some(v2) = e2.last() {
                e3.update(v2);
            }
        }
        let expected = e3.last().expect("ready");
        assert!((t3.last().expect("ready") - expected).abs() < 1e-9);
    }

    /// Naive reference: six independent EMA recursions, combined via the
    /// Tillson coefficients for a mid-range volume factor.
    #[test]
    fn t3_matches_naive_reference() {
        let rng = romu::Rng::from_seed_with_64bit(44);
        let window_len = 6usize;
        let v = 0.7_f64;
        let alpha = 2.0 / (window_len as f64 + 1.0);
        let (c1, c2, c3, c4) = (
            -v.powi(3),
            3.0 * v.powi(2) + 3.0 * v.powi(3),
            -6.0 * v.powi(2) - 3.0 * v - 3.0 * v.powi(3),
            1.0 + 3.0 * v + v.powi(3) + 3.0 * v.powi(2),
        );
        let vals: Vec<f64> = (0..400).map(|_| rng.f64() * 50.0).collect();

        let mut t3 = T3::new(Echo::new(), NonZeroUsize::new(window_len).unwrap());
        let mut emas: [Option<f64>; 6] = [None; 6];
        for val in vals.iter() {
            t3.update(*val);
            let mut input = *val;
            for e in emas.iter_mut() {
                *e = Some(match *e {
                    None => input,
                    Some(prev) => input * alpha + prev * (1.0 - alpha),
                });
                input = e.expect("set above");
            }
        }
        let [_, _, e3, e4, e5, e6] = emas.map(|e| e.expect("set"));
        let expected = c1 * e6 + c2 * e5 + c3 * e4 + c4 * e3;
        assert!((t3.last().expect("ready") - expected).abs() < 1e-6);
    }

    #[test]
    #[should_panic(expected = "volume_factor must be <= 1")]
    fn volume_factor_above_one_is_rejected() {
        let _ = T3::<f64, _>::with_volume_factor(Echo::new(), NonZeroUsize::new(5).unwrap(), 1.1);
    }

    #[test]
    #[should_panic(expected = "volume_factor must be >= 0")]
    fn negative_volume_factor_is_rejected() {
        let _ = T3::<f64, _>::with_volume_factor(Echo::new(), NonZeroUsize::new(5).unwrap(), -0.1);
    }

    #[test]
    fn t3_plot() {
        let mut t3 = T3::new(Echo::new(), NonZeroUsize::new(5).unwrap());
        let mut out: Vec<f64> = Vec::new();
        for v in &TEST_DATA {
            t3.update(*v);
            if let Some(val) = t3.last() {
                out.push(val);
            }
        }
        let filename = "img/t3.png";
        plot_values(out, filename).unwrap();
    }
}
