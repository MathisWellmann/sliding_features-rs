use std::{
    f64::consts::PI,
    num::NonZeroUsize,
};

use getset::CopyGetters;
use num::Float;

use crate::View;

/// John Ehlers two-pole band-pass filter.
///
/// Passes cycles with a period near `period` with unit gain and attenuates
/// both longer periods (trend) and shorter periods (noise).
/// `bandwidth` (delta) is the relative width of the pass band:
/// smaller values give a narrower band but a longer ringing time.
///
/// Reference: John Ehlers, "Cycle Analytics for Traders" (2013), chapter 5,
/// and John Ehlers and Ric Way, "Empirical Mode Decomposition" (2010),
/// <https://mesasoftware.com/papers/EmpiricalModeDecomposition.pdf>:
///
/// ```text
/// L1 = cos(2pi / P)
/// G1 = cos(delta * 2pi / P)
/// S1 = 1 / G1 - sqrt(1 / G1^2 - 1)
/// BP = 0.5 (1 - S1) (x - x[2]) + L1 (1 + S1) BP[1] - S1 BP[2]
/// ```
///
/// Deviations: the "Empirical Mode Decomposition" article uses
/// `cos(720 * delta / P)`, i.e. its `delta` is half of the `bandwidth` used here.
/// The book version additionally applies a one-pole high-pass before, and an
/// automatic gain control plus trigger line after this filter;
/// those stages are not included, so the output keeps the input's scale.
/// They can be composed with other views, e.g. [`HighPass`](super::HighPass).
/// The input history is seeded with the first value, so the filter starts at
/// rest (`BP = 0`), replacing Ehlers' `If CurrentBar < 3 Then BP = 0`.
/// `last()` is `None` for the first `period - 1` values.
///
/// Output range: unbounded, oscillates around 0. Constant input yields 0.
/// Complexity: O(1) per update, O(1) memory.
#[derive(Debug, Clone, CopyGetters)]
pub struct BandPass<T, V> {
    view: V,
    /// The center period of the pass band.
    #[getset(get_copy = "pub")]
    period: NonZeroUsize,
    bandwidth: T,
    /// Gain applied to `x - x[2]`, `0.5 (1 - S1)`.
    c_in: T,
    /// Feedback coefficient of `BP[1]`, `L1 (1 + S1)`.
    c_bp_1: T,
    /// Feedback coefficient of `BP[2]`, `-S1`.
    c_bp_2: T,
    /// Number of values received from the inner view.
    n: usize,
    val_1: T,
    val_2: T,
    bp: T,
    bp_1: T,
}

impl<T, V> BandPass<T, V>
where
    V: View<T>,
    T: Float,
{
    /// Create a new band-pass filter with a chained `View`.
    ///
    /// # Panics
    /// - If `period < 2`, as shorter periods are above the Nyquist frequency.
    /// - If `bandwidth` is not in `(0, 1)`.
    pub fn new(view: V, period: NonZeroUsize, bandwidth: T) -> Self {
        assert!(period.get() >= 2, "period must be >= 2");
        assert!(bandwidth > T::zero(), "bandwidth must be > 0");
        assert!(bandwidth < T::one(), "bandwidth must be < 1");
        let p = T::from(period.get()).expect("can convert");
        // G1 = cos(theta) must be positive for S1 to be real and inside (0, 1),
        // i.e. theta = bandwidth * 2pi / P < pi / 2.
        assert!(
            T::from(4.0).expect("can convert") * bandwidth < p,
            "bandwidth must be < period / 4 so that cos(bandwidth * 2pi / period) > 0"
        );
        let angle = T::from(2.0 * PI).expect("can convert") / p;
        let l1 = angle.cos();
        let theta = bandwidth * angle;
        // Algebraically equal to `1 / G1 - sqrt(1 / G1^2 - 1)` with `G1 = cos(theta)`,
        // but without the cancellation of two large terms when G1 is close to 0.
        let s1 = theta.cos() / (T::one() + theta.sin());
        assert!(s1 > T::zero(), "S1 must be positive");
        assert!(s1 < T::one(), "S1 must be below 1 for a stable filter");
        let half = T::from(0.5).expect("can convert");

        Self {
            view,
            period,
            bandwidth,
            c_in: half * (T::one() - s1),
            c_bp_1: l1 * (T::one() + s1),
            c_bp_2: -s1,
            n: 0,
            val_1: T::zero(),
            val_2: T::zero(),
            bp: T::zero(),
            bp_1: T::zero(),
        }
    }

    /// The relative bandwidth (delta) of the pass band, in `(0, 1)`.
    // Not generated by `getset`, as its impl block lacks the `T: Copy` bound.
    #[inline]
    pub fn bandwidth(&self) -> T {
        self.bandwidth
    }
}

impl<T, V> View<T> for BandPass<T, V>
where
    V: View<T>,
    T: Float,
{
    fn update(&mut self, val: T) {
        debug_assert!(val.is_finite(), "value must be finite");
        self.view.update(val);
        let Some(val) = self.view.last() else { return };
        debug_assert!(val.is_finite(), "value must be finite");

        if self.n == 0 {
            // Start at rest, see struct docs.
            self.val_1 = val;
            self.val_2 = val;
        }
        let bp = self.c_in * (val - self.val_2) + self.c_bp_1 * self.bp + self.c_bp_2 * self.bp_1;
        debug_assert!(bp.is_finite(), "filter output must be finite");
        self.bp_1 = self.bp;
        self.bp = bp;
        self.val_2 = self.val_1;
        self.val_1 = val;
        self.n = self.n.saturating_add(1);
    }

    #[inline]
    fn last(&self) -> Option<T> {
        if self.n < self.period.get() {
            return None;
        }
        debug_assert!(self.bp.is_finite(), "value must be finite");
        Some(self.bp)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::{
        plot::plot_values,
        pure_functions::Echo,
        test_data::TEST_DATA,
    };

    fn bp(period: usize, bandwidth: f64) -> BandPass<f64, Echo<f64>> {
        BandPass::new(Echo::new(), NonZeroUsize::new(period).unwrap(), bandwidth)
    }

    /// Steady state amplitude of the filter output for a unit sine input.
    fn sine_gain(period: usize, bandwidth: f64, sine_period: f64) -> f64 {
        let mut f = bp(period, bandwidth);
        let n = (60.0 * sine_period.max(period as f64)) as usize;
        let mut max_abs: f64 = 0.0;
        for i in 0..n {
            f.update((2.0 * PI * i as f64 / sine_period).sin());
            // Only measure the last few cycles, after the transient has decayed.
            if i > n - 4 * sine_period as usize {
                max_abs = max_abs.max(f.last().unwrap().abs());
            }
        }
        max_abs
    }

    #[test]
    fn band_pass_plot() {
        let mut f = bp(20, 0.3);
        let mut out: Vec<f64> = Vec::with_capacity(TEST_DATA.len());
        for v in &TEST_DATA {
            f.update(*v);
            if let Some(val) = f.last() {
                out.push(val);
            }
        }
        plot_values(out, "img/band_pass.png").unwrap();
    }

    #[test]
    fn band_pass_warmup() {
        let mut f = bp(10, 0.3);
        assert_eq!(f.period().get(), 10);
        assert_eq!(f.bandwidth(), 0.3);
        for i in 0..9 {
            f.update(i as f64);
            assert_eq!(f.last(), None);
        }
        f.update(9.0);
        assert!(f.last().is_some());
    }

    #[test]
    fn band_pass_hand_computed() {
        let (p, delta) = (10, 0.3);
        let mut f = bp(p, delta);
        let l1 = (2.0 * PI / p as f64).cos();
        let g1 = (delta * 2.0 * PI / p as f64).cos();
        let s1 = 1.0 / g1 - (1.0 / (g1 * g1) - 1.0).sqrt();
        let rng = romu::Rng::from_seed_with_64bit(5);
        let vals: Vec<f64> = (0..50).map(|_| rng.f64() * 10.0).collect();
        let (mut x1, mut x2, mut b1, mut b2) = (vals[0], vals[0], 0.0, 0.0);
        for v in vals {
            let b = 0.5 * (1.0 - s1) * (v - x2) + l1 * (1.0 + s1) * b1 - s1 * b2;
            (x2, x1, b2, b1) = (x1, v, b1, b);
            f.update(v);
        }
        assert!((f.last().unwrap() - b1).abs() < 1e-12);
    }

    #[test]
    fn band_pass_constant_input_is_zero() {
        let mut f = bp(20, 0.3);
        for _ in 0..100 {
            f.update(42.0);
        }
        assert_eq!(f.last(), Some(0.0));
    }

    #[test]
    fn band_pass_step_decays_to_zero() {
        let mut f = bp(20, 0.3);
        for i in 0..2_000 {
            f.update(if i < 50 { 1.0 } else { 5.0 });
        }
        assert!(f.last().unwrap().abs() < 1e-9);
    }

    #[test]
    fn band_pass_frequency_response() {
        for delta in [0.1, 0.3, 0.6] {
            let center = sine_gain(20, delta, 20.0);
            assert!(
                (0.95..1.05).contains(&center),
                "delta {delta}: center gain {center}"
            );
        }
        for sine_period in [4.0, 100.0] {
            let gain = sine_gain(20, 0.2, sine_period);
            assert!(gain < 0.2, "period {sine_period}: gain {gain}");
        }
        // A wider band passes off-center periods better.
        assert!(sine_gain(20, 0.6, 30.0) > sine_gain(20, 0.1, 30.0));
    }

    #[test]
    fn band_pass_edge_parameters_valid() {
        let mut f = bp(2, 0.4999);
        let mut g = bp(4, 0.99);
        let rng = romu::Rng::from_seed_with_64bit(3);
        for _ in 0..10_000 {
            let v = rng.f64();
            f.update(v);
            g.update(v);
        }
        assert!(f.last().unwrap().abs() < 10.0);
        assert!(g.last().unwrap().abs() < 10.0);
    }

    #[test]
    #[should_panic(expected = "period must be >= 2")]
    fn band_pass_period_too_small() {
        let _ = bp(1, 0.1);
    }

    #[test]
    #[should_panic(expected = "bandwidth must be > 0")]
    fn band_pass_bandwidth_zero() {
        let _ = bp(20, 0.0);
    }

    #[test]
    #[should_panic(expected = "bandwidth must be < 1")]
    fn band_pass_bandwidth_one() {
        let _ = bp(20, 1.0);
    }

    #[test]
    #[should_panic(expected = "bandwidth must be < period / 4")]
    fn band_pass_bandwidth_at_edge_for_period() {
        let _ = bp(2, 0.5);
    }

    #[test]
    #[should_panic(expected = "bandwidth must be < period / 4")]
    fn band_pass_bandwidth_too_wide_for_period() {
        let _ = bp(2, 0.5000001);
    }
}
