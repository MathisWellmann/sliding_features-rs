//! McGinley Dynamic

use std::num::NonZeroUsize;

use getset::CopyGetters;
use num::Float;

use crate::View;

/// McGinley Dynamic (John R. McGinley, "Fine Tuning The Moving Average",
/// Technical Analysis of Stocks & Commodities, 1997): a moving average that
/// adjusts its own speed to the market, tracking price more closely than a
/// plain moving average of the same length in both slow and fast markets.
///
/// `MD = MD[1] + (x - MD[1]) / (k * n * (x / MD[1])^4)`, seeded with the
/// first value. `n` is `window_len` and `k` is a constant (default `0.6`,
/// per the original article) controlling the adjustment speed.
///
/// Requires strictly positive input, since `x / MD[1]` is a ratio that would
/// be undefined or sign-flipping at zero or negative values.
///
/// Unlike a windowed average, `last()` is `Some` from the very first update:
/// this is a recursive filter seeded with `x`, not an average over a fixed
/// number of values, so it has no warm-up.
///
/// The `(x / MD)^4` term is a known source of instability: a large drop of
/// the input shrinks the denominator below 1, so the raw formula overshoots
/// far past the new value, can turn negative and then diverge. The step
/// `1 / (k * n * (x / MD[1])^4)` is therefore capped at 1: `MD` moves at
/// most to the new value, so it stays positive, finite and within the range
/// of the input. A real (autocorrelated) price series with `k * n >= 1`
/// rarely reaches the cap, so it rarely changes the original formula.
///
/// Complexity: O(1) per update; O(1) memory.
#[derive(Debug, Clone, CopyGetters)]
pub struct McGinleyDynamic<T, V> {
    view: V,
    /// The non-zero window length `n`.
    #[getset(get_copy = "pub")]
    window_len: NonZeroUsize,
    k: T,
    last_md: Option<T>,
}

impl<T, V> McGinleyDynamic<T, V>
where
    V: View<T>,
    T: Float,
{
    /// Create a new McGinley Dynamic with a chained `View`, a window length
    /// and the default constant `k = 0.6`.
    pub fn new(view: V, window_len: NonZeroUsize) -> Self {
        Self::with_k(view, window_len, T::from(0.6).expect("can convert"))
    }

    /// Create a new McGinley Dynamic with a chained `View`, a window length
    /// and a custom constant `k`.
    ///
    /// # Panics
    /// If `k` is not strictly positive.
    pub fn with_k(view: V, window_len: NonZeroUsize, k: T) -> Self {
        assert!(k > T::zero(), "k must be > 0");
        Self {
            view,
            window_len,
            k,
            last_md: None,
        }
    }

    /// The adjustment constant `k`.
    // Not generated by `getset`, as its impl block lacks the `T: Copy` bound.
    #[inline]
    pub fn k(&self) -> T {
        self.k
    }
}

impl<T, V> View<T> for McGinleyDynamic<T, V>
where
    V: View<T>,
    T: Float,
{
    fn update(&mut self, val: T) {
        debug_assert!(val.is_finite(), "value must be finite");
        self.view.update(val);
        let Some(val) = self.view.last() else { return };
        debug_assert!(val.is_finite(), "value must be finite");
        debug_assert!(val > T::zero(), "McGinley Dynamic requires positive input");

        self.last_md = Some(match self.last_md {
            None => val,
            Some(prev) => {
                let n = T::from(self.window_len.get()).expect("can convert");
                let ratio = val / prev;
                let denom = self.k * n * ratio.powi(4);
                // Capped so that a drop never overshoots the new value (a
                // denominator that underflows to 0 gives a step of 1).
                let step = (T::one() / denom).min(T::one());
                debug_assert!(step >= T::zero(), "the denominator is positive");
                prev + (val - prev) * step
            }
        });
    }

    fn last(&self) -> Option<T> {
        self.last_md.inspect(|v| {
            debug_assert!(v.is_finite(), "value must be finite");
        })
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::{
        plot::plot_values,
        pure_functions::Echo,
        test_data::TEST_DATA,
    };

    #[test]
    fn mc_ginley_dynamic_is_ready_from_the_first_update() {
        let mut md = McGinleyDynamic::new(Echo::new(), NonZeroUsize::new(10).unwrap());
        assert_eq!(md.last(), None);
        md.update(5.0);
        assert_eq!(md.last(), Some(5.0));
        md.update(5.5);
        assert!(md.last().is_some());
    }

    #[test]
    fn mc_ginley_dynamic_constant_input_is_the_constant() {
        let mut md = McGinleyDynamic::new(Echo::new(), NonZeroUsize::new(10).unwrap());
        for _ in 0..20 {
            md.update(12.0);
        }
        assert_eq!(md.last(), Some(12.0));
    }

    /// Naive reference: the formula applied directly, step by step.
    ///
    /// Uses a gentle random walk rather than i.i.d. uniform noise, so the
    /// step stays below its cap and the raw formula applies.
    #[test]
    fn mc_ginley_dynamic_matches_naive_reference() {
        let rng = romu::Rng::from_seed_with_64bit(99);
        let window_len = 10usize;
        let k = 0.6;
        let mut price = 100.0_f64;
        let vals: Vec<f64> = (0..300)
            .map(|_| {
                price *= 1.0 + 0.01 * (rng.f64() - 0.5);
                price
            })
            .collect();

        let mut md = McGinleyDynamic::new(Echo::new(), NonZeroUsize::new(window_len).unwrap());
        let mut naive: Option<f64> = None;
        for v in vals.iter() {
            md.update(*v);
            naive = Some(match naive {
                None => *v,
                Some(prev) => prev + (v - prev) / (k * window_len as f64 * (v / prev).powi(4)),
            });
            let got = md.last().expect("always ready");
            assert!((got - naive.expect("set above")).abs() < 1e-9);
        }
    }

    /// A drop to a sixth made the raw formula overshoot to about -1e16,
    /// then diverge to infinity on the next value.
    #[test]
    fn mc_ginley_dynamic_does_not_overshoot_a_drop() {
        let mut md = McGinleyDynamic::new(Echo::new(), NonZeroUsize::new(1).unwrap());
        for v in [1e12, 2e12, 3e12, 4e12, 5e12, 6e12, 1e12, 2e12, 3e12] {
            md.update(v);
            let got = md.last().expect("always ready");
            assert!((1e12..=6e12).contains(&got), "{got}");
        }
        let mut md = McGinleyDynamic::new(Echo::new(), NonZeroUsize::new(10).unwrap());
        md.update(6.0);
        md.update(1.0);
        assert_eq!(md.last(), Some(1.0), "the step is capped at the new value");
    }

    #[test]
    #[should_panic(expected = "k must be > 0")]
    fn zero_k_is_rejected() {
        let _ = McGinleyDynamic::<f64, _>::with_k(Echo::new(), NonZeroUsize::new(10).unwrap(), 0.0);
    }

    #[test]
    #[should_panic(expected = "k must be > 0")]
    fn negative_k_is_rejected() {
        let _ =
            McGinleyDynamic::<f64, _>::with_k(Echo::new(), NonZeroUsize::new(10).unwrap(), -0.1);
    }

    #[test]
    fn mc_ginley_dynamic_plot() {
        let mut md = McGinleyDynamic::new(Echo::new(), NonZeroUsize::new(16).unwrap());
        let mut out: Vec<f64> = Vec::new();
        for v in &TEST_DATA {
            md.update(*v);
            if let Some(val) = md.last() {
                out.push(val);
            }
        }
        let filename = "img/mc_ginley_dynamic.png";
        plot_values(out, filename).unwrap();
    }
}
