use std::{
    f64::consts::PI,
    num::NonZeroUsize,
};

use getset::CopyGetters;
use num::Float;

use crate::View;

/// Number of poles of a [`GaussianFilter`].
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum GaussianPoles {
    /// One pole, identical to an EMA with the Gaussian `alpha`.
    One,
    /// Two poles.
    Two,
    /// Three poles.
    Three,
    /// Four poles: the best high frequency rejection, but the most lag.
    Four,
}

impl GaussianPoles {
    /// The number of poles as a count.
    fn count(self) -> usize {
        match self {
            Self::One => 1,
            Self::Two => 2,
            Self::Three => 3,
            Self::Four => 4,
        }
    }
}

/// Maximum number of poles, the number of EMA stages.
const MAX_POLES: usize = 4;

/// John Ehlers Gaussian filter with one to four poles.
///
/// `N` cascaded EMAs with the same `alpha`, which approximates a Gaussian
/// impulse response. `alpha` is chosen so that the gain at `period` is
/// `1/sqrt(2)` (-3 dB) for every number of poles; more poles reject shorter
/// periods better at the cost of more lag.
///
/// Reference: John Ehlers, "Gaussian and Other Low Lag Filters" (2002),
/// <https://www.mesasoftware.com/papers/GaussianFilters.pdf>:
///
/// ```text
/// beta  = (1 - cos(2pi / P)) / (2^(1/N) - 1)
/// alpha = -beta + sqrt(beta^2 + 2 beta)
/// f = alpha^N x + sum_{k=1}^{N} (-1)^(k+1) binomial(N, k) (1 - alpha)^k f[k]
/// ```
///
/// e.g. for two poles `f = alpha^2 x + 2(1 - alpha) f[1] - (1 - alpha)^2 f[2]`.
///
/// Deviations:
/// - The filter is computed as the cascade of `N` EMAs, which is
///   algebraically identical to the paper's recursion. The recursion's
///   feedback coefficients round to an unstable filter at long periods
///   (four poles diverge at period 1e6 and leave the input range at 1e5),
///   while each EMA is stable and the cascade stays within the input range.
/// - `1 - cos(2pi / P)` is computed as `2 sin^2(pi / P)`, which does not
///   round to 0 (and `alpha` to 0) for periods above about 4e8.
/// - The stages are seeded with the first input, so the filter starts at
///   rest instead of rising from 0 as in EasyLanguage.
///
/// `last()` is `None` for the first `period - 1` values.
///
/// Output range: within the range of the inputs seen so far.
/// Constant input yields the constant.
/// Complexity: O(N) = O(1) per update (`N <= 4`), O(1) memory.
#[derive(Debug, Clone, CopyGetters)]
pub struct GaussianFilter<T, V> {
    view: V,
    /// The critical period at which the gain is -3 dB.
    #[getset(get_copy = "pub")]
    period: NonZeroUsize,
    /// The number of poles.
    #[getset(get_copy = "pub")]
    poles: GaussianPoles,
    alpha: T,
    /// The EMA stages, the input of each is the previous one; unused beyond `N`.
    stages: [T; MAX_POLES],
    /// Number of values received from the inner view.
    n: usize,
}

impl<T, V> GaussianFilter<T, V>
where
    V: View<T>,
    T: Float,
{
    /// Create a new Gaussian filter with a chained `View`.
    ///
    /// # Panics
    /// If `period < 2`, as shorter periods are above the Nyquist frequency.
    pub fn new(view: V, period: NonZeroUsize, poles: GaussianPoles) -> Self {
        assert!(period.get() >= 2, "period must be >= 2");
        let n_t = T::from(poles.count()).expect("can convert");
        let two = T::from(2.0).expect("can convert");
        let half_angle =
            T::from(PI).expect("can convert") / T::from(period.get()).expect("can convert");
        // `1 - cos(2x) = 2 sin^2(x)`, without the cancellation for small `x`.
        let one_minus_cos = two * half_angle.sin() * half_angle.sin();
        let beta = one_minus_cos / (two.powf(T::one() / n_t) - T::one());
        let alpha = -beta + (beta * beta + two * beta).sqrt();
        assert!(alpha > T::zero(), "alpha must be positive");
        assert!(
            alpha < T::one(),
            "alpha must be below 1 for a stable filter"
        );
        Self {
            view,
            period,
            poles,
            alpha,
            stages: [T::zero(); MAX_POLES],
            n: 0,
        }
    }

    /// The smoothing factor of each pole, in `(0, 1)`.
    // Not generated by `getset`, as its impl block lacks the `T: Copy` bound.
    #[inline]
    pub fn alpha(&self) -> T {
        self.alpha
    }
}

impl<T, V> View<T> for GaussianFilter<T, V>
where
    V: View<T>,
    T: Float,
{
    fn update(&mut self, val: T) {
        debug_assert!(val.is_finite(), "value must be finite");
        self.view.update(val);
        let Some(val) = self.view.last() else { return };
        debug_assert!(val.is_finite(), "value must be finite");

        if self.n == 0 {
            // Start at rest, see struct docs.
            self.stages = [val; MAX_POLES];
        }
        let one_minus = T::one() - self.alpha;
        let mut input = val;
        for stage in self.stages.iter_mut().take(self.poles.count()) {
            *stage = self.alpha * input + one_minus * *stage;
            input = *stage;
        }
        debug_assert!(input.is_finite(), "filter output must be finite");
        self.n = self.n.saturating_add(1);
    }

    #[inline]
    fn last(&self) -> Option<T> {
        if self.n < self.period.get() {
            return None;
        }
        let out = self.stages[self.poles.count() - 1];
        debug_assert!(out.is_finite(), "value must be finite");
        Some(out)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::{
        plot::plot_values,
        pure_functions::Echo,
        test_data::TEST_DATA,
    };

    const POLES: [GaussianPoles; 4] = [
        GaussianPoles::One,
        GaussianPoles::Two,
        GaussianPoles::Three,
        GaussianPoles::Four,
    ];

    fn gauss(period: usize, poles: GaussianPoles) -> GaussianFilter<f64, Echo<f64>> {
        GaussianFilter::new(Echo::new(), NonZeroUsize::new(period).unwrap(), poles)
    }

    /// Steady state amplitude for a unit sine with an integer period, from the RMS
    /// over whole cycles, so it does not depend on where the samples hit the peak.
    fn sine_gain(period: usize, poles: GaussianPoles, sine_period: usize) -> f64 {
        let mut f = gauss(period, poles);
        let n = 100 * sine_period.max(period);
        let mut sum_sq = 0.0;
        for i in 0..n {
            f.update((2.0 * PI * i as f64 / sine_period as f64).sin());
            if i >= n - 10 * sine_period {
                sum_sq += f.last().unwrap().powi(2);
            }
        }
        (2.0 * sum_sq / (10 * sine_period) as f64).sqrt()
    }

    #[test]
    fn gaussian_filter_plot() {
        let mut f = gauss(20, GaussianPoles::Four);
        let mut out: Vec<f64> = Vec::with_capacity(TEST_DATA.len());
        for v in &TEST_DATA {
            f.update(*v);
            if let Some(val) = f.last() {
                out.push(val);
            }
        }
        plot_values(out, "img/gaussian_filter.png").unwrap();
    }

    #[test]
    fn gaussian_filter_warmup() {
        for poles in POLES {
            let mut f = gauss(10, poles);
            assert_eq!(f.period().get(), 10);
            assert_eq!(f.poles(), poles);
            for i in 0..9 {
                f.update(i as f64);
                assert_eq!(f.last(), None);
            }
            f.update(9.0);
            assert!(f.last().is_some());
        }
    }

    #[test]
    fn gaussian_filter_matches_paper_recursions() {
        let p = 14;
        for poles in POLES {
            let mut f = gauss(p, poles);
            let n = poles.count() as f64;
            let beta = (1.0 - (2.0 * PI / p as f64).cos()) / (2.0_f64.powf(1.0 / n) - 1.0);
            let a = -beta + (beta * beta + 2.0 * beta).sqrt();
            assert!((f.alpha() - a).abs() < 1e-15);
            let b = 1.0 - a;
            let x0 = TEST_DATA[0];
            let (mut f1, mut f2, mut f3, mut f4) = (x0, x0, x0, x0);
            for (i, x) in TEST_DATA.iter().enumerate() {
                // The recursions as written out in the paper.
                let g = match poles {
                    GaussianPoles::One => a * x + b * f1,
                    GaussianPoles::Two => a.powi(2) * x + 2.0 * b * f1 - b.powi(2) * f2,
                    GaussianPoles::Three => {
                        a.powi(3) * x + 3.0 * b * f1 - 3.0 * b.powi(2) * f2 + b.powi(3) * f3
                    }
                    GaussianPoles::Four => {
                        a.powi(4) * x + 4.0 * b * f1 - 6.0 * b.powi(2) * f2 + 4.0 * b.powi(3) * f3
                            - b.powi(4) * f4
                    }
                };
                (f4, f3, f2, f1) = (f3, f2, f1, g);
                f.update(*x);
                if let Some(got) = f.last() {
                    assert!((got - g).abs() < 1e-9, "{poles:?} bar {i}: {got} vs {g}");
                }
            }
        }
    }

    #[test]
    fn gaussian_filter_constant_input() {
        for poles in POLES {
            let mut f = gauss(20, poles);
            for _ in 0..100 {
                f.update(42.0);
            }
            assert!((f.last().unwrap() - 42.0).abs() < 1e-10, "{poles:?}");
        }
    }

    #[test]
    fn gaussian_filter_minus_3db_at_period() {
        for poles in POLES {
            let g = sine_gain(20, poles, 20);
            assert!((g - 0.5_f64.sqrt()).abs() < 1e-3, "{poles:?}: gain {g}");
            let slow = sine_gain(20, poles, 400);
            assert!(slow > 0.99, "{poles:?}: slow gain {slow}");
        }
    }

    #[test]
    fn gaussian_filter_more_poles_reject_more() {
        let gains: Vec<f64> = POLES.iter().map(|p| sine_gain(20, *p, 5)).collect();
        for w in gains.windows(2) {
            assert!(w[1] < w[0], "{gains:?}");
        }
        assert!(gains[3] < 0.1, "{gains:?}");
    }

    /// The paper's direct-form recursion with four poles left `[0, 1]` by
    /// 1.4e-3 on this step at period 1e5, and diverged at period 1e6.
    #[test]
    fn gaussian_filter_long_periods_stay_in_the_input_range() {
        for poles in POLES {
            let mut f = gauss(100_000, poles);
            f.update(0.0);
            for _ in 0..300_000 {
                f.update(1.0);
                if let Some(out) = f.last() {
                    assert!((0.0..=1.0).contains(&out), "{poles:?}: {out}");
                }
            }
            assert!(f.last().unwrap() > 0.9, "{poles:?}");
        }
    }

    /// `1 - cos(2pi / P)` rounds to 0 above P ~ 4e8, which made alpha 0.
    #[test]
    fn gaussian_filter_huge_periods_have_a_positive_alpha() {
        for poles in POLES {
            let mut f = gauss(1 << 53, poles);
            assert!(f.alpha() > 0.0, "{poles:?}");
            f.update(1.0);
            f.update(2.0);
            assert_eq!(f.last(), None);
        }
    }

    #[test]
    #[should_panic(expected = "period must be >= 2")]
    fn gaussian_filter_period_too_small() {
        let _ = gauss(1, GaussianPoles::Two);
    }
}
