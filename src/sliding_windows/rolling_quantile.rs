//! Rolling quantile over a sliding window.

use std::num::NonZeroUsize;

use num::Float;

use super::sorted_window::SortedWindow;
use crate::View;

/// Rolling `q`-quantile of the last `window_len` values.
///
/// Uses linear interpolation between order statistics (Hyndman & Fan 1996,
/// "Sample Quantiles in Statistical Packages", type 7; the default of R's
/// `quantile` and numpy's `quantile`): with the sorted window `s` of length `n`,
/// `h = (n - 1) q` and `Q = s[floor(h)] + (h - floor(h)) (s[floor(h) + 1] - s[floor(h)])`.
/// `q = 0` is the minimum, `q = 0.5` the median and `q = 1` the maximum.
///
/// `last()` is `None` until `window_len` values were observed.
/// Output range: within the minimum and maximum of the window.
///
/// Complexity per update: O(log n) binary search plus an O(n) `memmove` in a
/// sorted `Vec` (fast for typical window sizes); O(1) for `last()`; O(n) memory.
#[derive(Debug, Clone)]
pub struct RollingQuantile<T, V> {
    view: V,
    q: T,
    window: SortedWindow<T>,
}

impl<T, V> RollingQuantile<T, V>
where
    V: View<T>,
    T: Float,
{
    /// Create a new rolling quantile with a chained `View`, a sliding window
    /// length and the quantile `q`.
    ///
    /// # Panics
    /// If `q` is not in `[0, 1]`.
    pub fn new(view: V, window_len: NonZeroUsize, q: T) -> Self {
        assert!(q >= T::zero(), "q must be >= 0");
        assert!(q <= T::one(), "q must be <= 1");
        Self {
            view,
            q,
            window: SortedWindow::new(window_len),
        }
    }

    /// The quantile in `[0, 1]` that is computed.
    // Not generated by `getset`, as its impl block lacks the `T: Copy` bound.
    #[inline]
    pub fn q(&self) -> T {
        self.q
    }

    /// The sliding window length.
    #[inline]
    pub fn window_len(&self) -> NonZeroUsize {
        self.window.window_len()
    }
}

impl<T, V> View<T> for RollingQuantile<T, V>
where
    V: View<T>,
    T: Float,
{
    fn update(&mut self, val: T) {
        debug_assert!(val.is_finite(), "value must be finite");
        self.view.update(val);
        let Some(val) = self.view.last() else { return };
        debug_assert!(val.is_finite(), "value must be finite");

        let _evicted = self.window.push(val);
    }

    #[inline]
    fn last(&self) -> Option<T> {
        if !self.window.is_full() {
            return None;
        }
        let out = self
            .window
            .quantile(self.q)
            .expect("a full window is not empty");
        debug_assert!(out.is_finite(), "value must be finite");
        Some(out)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::{
        plot::plot_values,
        pure_functions::Echo,
        test_data::TEST_DATA,
    };

    fn rq(window_len: usize, q: f64) -> RollingQuantile<f64, Echo<f64>> {
        RollingQuantile::new(Echo::new(), NonZeroUsize::new(window_len).unwrap(), q)
    }

    /// Naive type 7 quantile: sort a copy of the window.
    fn naive_quantile(window: &[f64], q: f64) -> f64 {
        let mut s = window.to_vec();
        s.sort_by(|a, b| a.partial_cmp(b).unwrap());
        let h = (s.len() - 1) as f64 * q;
        let lo = h.floor() as usize;
        let hi = (lo + 1).min(s.len() - 1);
        s[lo] + (h - lo as f64) * (s[hi] - s[lo])
    }

    #[test]
    fn rolling_quantile_plot() {
        let mut v = rq(32, 0.25);
        let mut out: Vec<f64> = Vec::with_capacity(TEST_DATA.len());
        for x in &TEST_DATA {
            v.update(*x);
            if let Some(val) = v.last() {
                out.push(val);
            }
        }
        plot_values(out, "img/rolling_quantile.png").unwrap();
    }

    #[test]
    fn rolling_quantile_warmup_and_hand_computed() {
        let mut v = rq(4, 0.25);
        assert_eq!(v.window_len().get(), 4);
        assert_eq!(v.q(), 0.25);
        for x in [3.0, 1.0, 4.0] {
            v.update(x);
            assert_eq!(v.last(), None);
        }
        v.update(2.0);
        // numpy.quantile([3, 1, 4, 2], 0.25) == 1.75
        assert_eq!(v.last(), Some(1.75));
        v.update(10.0);
        // numpy.quantile([1, 4, 2, 10], 0.25) == 1.75
        assert_eq!(v.last(), Some(1.75));
        v.update(0.0);
        // numpy.quantile([4, 2, 10, 0], 0.25) == 1.5
        assert_eq!(v.last(), Some(1.5));
    }

    #[test]
    fn rolling_quantile_vs_naive() {
        let rng = romu::Rng::from_seed_with_64bit(31);
        for window_len in [1, 2, 3, 10, 51] {
            for q in [0.0, 0.25, 0.5, 1.0, 0.9] {
                // Mix of continuous values and frequent duplicates.
                let vals: Vec<f64> = (0..2_000)
                    .map(|_| match rng.range_usize(0..3) {
                        0 => rng.f64() * 10.0,
                        _ => rng.range_usize(0..5) as f64,
                    })
                    .collect();
                let mut v = rq(window_len, q);
                for (i, x) in vals.iter().enumerate() {
                    v.update(*x);
                    if i + 1 < window_len {
                        assert_eq!(v.last(), None);
                        continue;
                    }
                    let expected = naive_quantile(&vals[i + 1 - window_len..=i], q);
                    assert_eq!(v.last(), Some(expected), "step {i}, n {window_len}, q {q}");
                }
            }
        }
    }

    #[test]
    fn rolling_quantile_constant_input() {
        let mut v = rq(5, 0.3);
        for _ in 0..20 {
            v.update(7.5);
        }
        assert_eq!(v.last(), Some(7.5));
    }

    #[test]
    fn rolling_quantile_edges_are_min_and_max() {
        let rng = romu::Rng::from_seed_with_64bit(32);
        let vals: Vec<f64> = (0..500).map(|_| rng.f64()).collect();
        let (mut lo, mut hi) = (rq(16, 0.0), rq(16, 1.0));
        for (i, x) in vals.iter().enumerate() {
            lo.update(*x);
            hi.update(*x);
            if i < 15 {
                continue;
            }
            let window = &vals[i - 15..=i];
            assert_eq!(
                lo.last(),
                Some(window.iter().copied().fold(f64::MAX, f64::min))
            );
            assert_eq!(
                hi.last(),
                Some(window.iter().copied().fold(f64::MIN, f64::max))
            );
        }
    }

    #[test]
    #[should_panic(expected = "q must be >= 0")]
    fn rolling_quantile_q_below_zero() {
        let _ = rq(5, -0.01);
    }

    #[test]
    #[should_panic(expected = "q must be <= 1")]
    fn rolling_quantile_q_above_one() {
        let _ = rq(5, 1.0 + f64::EPSILON);
    }

    #[test]
    #[should_panic(expected = "q must be >= 0")]
    fn rolling_quantile_q_nan() {
        let _ = rq(5, f64::NAN);
    }
}
