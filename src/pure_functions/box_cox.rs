use num::Float;

use crate::View;

/// The Box-Cox power transform (Box & Cox, 1964, "An Analysis of
/// Transformations") of the output of its `View` component, with a fixed
/// power parameter `lambda`:
///
/// ```text
/// y = (x^lambda - 1) / lambda   if lambda != 0
/// y = ln(x)                     if lambda == 0
/// ```
///
/// Used to stabilize variance and make positively skewed data more
/// normal-like ahead of models that assume normality; `lambda = 1` is the
/// identity shifted by `-1`, `lambda = 0` the natural logarithm, and
/// `lambda = 0.5` a (shifted, scaled) square root.
///
/// Like [`super::Ln`], Box-Cox is only defined for strictly positive input:
/// for zero or negative input, `last` is `None` rather than a non-finite
/// value. Use the `YeoJohnson` transform if the input can be zero or
/// negative. `last` is also `None` where the power overflows (e.g.
/// `1e12^30`).
#[derive(Debug, Clone)]
pub struct BoxCox<T, V> {
    view: V,
    lambda: T,
}

impl<T, V> BoxCox<T, V>
where
    V: View<T>,
    T: Float,
{
    /// Create a new Box-Cox transform with a chained `View` and a power
    /// parameter `lambda`.
    pub fn new(view: V, lambda: T) -> Self {
        Self { view, lambda }
    }

    /// The power parameter `lambda`.
    // Not generated by `getset`, as its impl block lacks the `T: Copy` bound.
    #[inline]
    pub fn lambda(&self) -> T {
        self.lambda
    }
}

impl<T, V> View<T> for BoxCox<T, V>
where
    V: View<T>,
    T: Float,
{
    fn update(&mut self, val: T) {
        debug_assert!(val.is_finite(), "value must be finite");
        self.view.update(val);
    }

    fn last(&self) -> Option<T> {
        let v = self.view.last()?;
        debug_assert!(v.is_finite(), "value must be finite");
        if v <= T::zero() {
            return None;
        }
        let out = if self.lambda == T::zero() {
            v.ln()
        } else {
            (v.powf(self.lambda) - T::one()) / self.lambda
        };
        // A large `|lambda|` overflows the power for finite input: not ready
        // there, rather than an infinity that downstream views assert against.
        out.is_finite().then_some(out)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::pure_functions::Echo;

    #[test]
    fn box_cox_overflow_is_none() {
        // 1e12^30 = 1e360 overflows: not ready instead of an infinity.
        let mut v = BoxCox::new(Echo::new(), 30.0);
        v.update(1e12);
        assert_eq!(v.last(), None);
        v.update(2.0);
        assert_eq!(v.last(), Some((2.0_f64.powi(30) - 1.0) / 30.0));
        let mut v = BoxCox::new(Echo::new(), -30.0);
        v.update(1e-12);
        assert_eq!(v.last(), None);
    }

    #[test]
    fn box_cox_lambda_zero_is_ln() {
        let mut v = BoxCox::new(Echo::new(), 0.0);
        assert_eq!(v.lambda(), 0.0);
        v.update(std::f64::consts::E);
        assert!((v.last().expect("positive input") - 1.0).abs() < 1e-12);
    }

    #[test]
    fn box_cox_lambda_one_is_shifted_identity() {
        let mut v = BoxCox::new(Echo::new(), 1.0);
        v.update(5.0);
        // (5^1 - 1) / 1 == 4
        assert_eq!(v.last(), Some(4.0));
    }

    #[test]
    fn box_cox_lambda_half_is_shifted_scaled_sqrt() {
        let mut v = BoxCox::new(Echo::new(), 0.5);
        v.update(4.0);
        // (4^0.5 - 1) / 0.5 == (2 - 1) / 0.5 == 2
        assert!((v.last().expect("positive input") - 2.0).abs() < 1e-12);
    }

    #[test]
    fn box_cox_negative_lambda() {
        let mut v = BoxCox::new(Echo::new(), -1.0);
        v.update(2.0);
        // (2^-1 - 1) / -1 == (0.5 - 1) / -1 == 0.5
        assert!((v.last().expect("positive input") - 0.5).abs() < 1e-12);
    }

    #[test]
    fn box_cox_non_positive_input_is_none() {
        let mut v = BoxCox::new(Echo::new(), 0.5);
        v.update(0.0);
        assert_eq!(v.last(), None);
        v.update(-1.0);
        assert_eq!(v.last(), None);
    }

    #[test]
    fn box_cox_vs_naive() {
        let rng = romu::Rng::from_seed_with_64bit(81);
        for lambda in [-2.0, -0.5, 0.0, 0.5, 1.0, 2.0] {
            let mut v = BoxCox::new(Echo::new(), lambda);
            for _ in 0..200 {
                let x = rng.f64() * 100.0 + 1e-6;
                v.update(x);
                let expected = if lambda == 0.0 {
                    x.ln()
                } else {
                    (x.powf(lambda) - 1.0) / lambda
                };
                assert!(
                    (v.last().expect("positive input") - expected).abs() < 1e-9,
                    "lambda {lambda}, x {x}"
                );
            }
        }
    }
}
