use num::Float;

use crate::View;

/// The Yeo-Johnson power transform (Yeo & Johnson, 2000, "A new family of
/// power transformations to improve normality or symmetry") of the output
/// of its `View` component, with a fixed power parameter `lambda`:
///
/// ```text
/// y =  ((x + 1)^lambda - 1) / lambda        if x >= 0, lambda != 0
/// y =  ln(x + 1)                            if x >= 0, lambda == 0
/// y = -((-x + 1)^(2 - lambda) - 1) / (2 - lambda)   if x < 0, lambda != 2
/// y = -ln(-x + 1)                           if x < 0, lambda == 2
/// ```
///
/// Reduces to `BoxCox` applied to `x + 1` for non-negative input, but unlike
/// `BoxCox`, is defined for every finite `x`, not only strictly positive
/// input: this makes it applicable to e.g. returns or any signed feature,
/// without first shifting the data to be positive. `last` is `None` where
/// the power overflows (e.g. `(1e12 + 1)^30`).
#[derive(Debug, Clone)]
pub struct YeoJohnson<T, V> {
    view: V,
    lambda: T,
}

impl<T, V> YeoJohnson<T, V>
where
    V: View<T>,
    T: Float,
{
    /// Create a new Yeo-Johnson transform with a chained `View` and a power
    /// parameter `lambda`.
    pub fn new(view: V, lambda: T) -> Self {
        Self { view, lambda }
    }

    /// The power parameter `lambda`.
    // Not generated by `getset`, as its impl block lacks the `T: Copy` bound.
    #[inline]
    pub fn lambda(&self) -> T {
        self.lambda
    }
}

impl<T, V> View<T> for YeoJohnson<T, V>
where
    V: View<T>,
    T: Float,
{
    fn update(&mut self, val: T) {
        debug_assert!(val.is_finite(), "value must be finite");
        self.view.update(val);
    }

    fn last(&self) -> Option<T> {
        let v = self.view.last()?;
        debug_assert!(v.is_finite(), "value must be finite");
        let out = yeo_johnson(v, self.lambda);
        // A large `|lambda|` overflows the power for finite input: not ready
        // there, rather than an infinity that downstream views assert against.
        out.is_finite().then_some(out)
    }
}

/// The scalar Yeo-Johnson transform, split out from `last` for testability
/// against a naive reference without needing a `View` chain.
fn yeo_johnson<T: Float>(x: T, lambda: T) -> T {
    let one = T::one();
    let two = T::from(2.0).expect("can convert");
    if x >= T::zero() {
        if lambda == T::zero() {
            (x + one).ln()
        } else {
            ((x + one).powf(lambda) - one) / lambda
        }
    } else if lambda == two {
        -(-x + one).ln()
    } else {
        -((-x + one).powf(two - lambda) - one) / (two - lambda)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::pure_functions::Echo;

    fn yj(lambda: f64) -> YeoJohnson<f64, Echo<f64>> {
        YeoJohnson::new(Echo::new(), lambda)
    }

    #[test]
    fn yeo_johnson_overflow_is_none() {
        // (1e12 + 1)^30 overflows, and so does (1e12 + 1)^(2 + 30).
        let mut v = yj(30.0);
        v.update(1e12);
        assert_eq!(v.last(), None);
        let mut v = yj(-30.0);
        v.update(-1e12);
        assert_eq!(v.last(), None);
        v.update(-1.0);
        assert!(v.last().is_some_and(f64::is_finite));
    }

    #[test]
    fn yeo_johnson_lambda_one_is_identity() {
        let mut v = yj(1.0);
        v.update(5.0);
        assert_eq!(v.last(), Some(5.0));
        v.update(-3.0);
        assert_eq!(v.last(), Some(-3.0));
    }

    #[test]
    fn yeo_johnson_zero_is_zero_for_every_lambda() {
        for lambda in [-2.0, -0.5, 0.0, 0.5, 1.0, 1.5, 2.0, 3.0] {
            let mut v = yj(lambda);
            v.update(0.0);
            assert!(
                (v.last().expect("defined for every finite x") - 0.0).abs() < 1e-12,
                "lambda {lambda}"
            );
        }
    }

    #[test]
    fn yeo_johnson_nonnegative_lambda_zero_is_ln_shifted() {
        let mut v = yj(0.0);
        v.update(std::f64::consts::E - 1.0);
        assert!((v.last().expect("defined") - 1.0).abs() < 1e-12);
    }

    #[test]
    fn yeo_johnson_negative_lambda_two_is_negative_ln_shifted() {
        let mut v = yj(2.0);
        v.update(1.0 - std::f64::consts::E);
        assert!((v.last().expect("defined") - (-1.0)).abs() < 1e-12);
    }

    #[test]
    fn yeo_johnson_is_defined_for_negative_input() {
        let mut v = yj(0.5);
        v.update(-10.0);
        assert!(v.last().is_some());
    }

    #[test]
    fn yeo_johnson_vs_naive() {
        let rng = romu::Rng::from_seed_with_64bit(91);
        for lambda in [-1.0, -0.5, 0.0, 0.5, 1.0, 1.5, 2.0, 2.5] {
            let mut v = yj(lambda);
            for _ in 0..300 {
                let x = rng.f64() * 200.0 - 100.0;
                v.update(x);
                let expected = if x >= 0.0 {
                    if lambda == 0.0 {
                        (x + 1.0).ln()
                    } else {
                        ((x + 1.0).powf(lambda) - 1.0) / lambda
                    }
                } else if lambda == 2.0 {
                    -(-x + 1.0).ln()
                } else {
                    -((-x + 1.0).powf(2.0 - lambda) - 1.0) / (2.0 - lambda)
                };
                assert!(
                    (v.last().expect("defined") - expected).abs() < 1e-9,
                    "lambda {lambda}, x {x}"
                );
            }
        }
    }
}
